test('demo runs staffed dispatch, player verification, correction, handoff, finalization, and detached rulings in the shared runtime',async()=>{
 const demo=await createDemoRuntime(Date.now()+120000);
 const independent=await createDemoRuntime(Date.now()+120000);
 const orgAction=async (body, expectedRevision) => request(demo,'/api/umpires','POST',{...body,expectedRevision:expectedRevision ?? (await snapshot(demo)).revision});
 const seat=(name,body)=>request(demo,'/api/umpires',body?'POST':'GET',body,{'x-demo-umpire-seat':name});
 const get=async name=>(await seat(name)).json();
 const stateAction=async body=>request(demo,'/api/state','POST',{...body,expectedRevision:(await snapshot(demo)).revision});
 const check=async (result,status=200)=>{
  const response=await result;const data=await response.json();assert.equal(response.status,status,JSON.stringify(data));return data;
 };
 const score=async(name,sets)=>{const {match}=await get(name);return seat(name,{action:'score',matchId:match.id,version:match.umpireWorkflow.version,operation:crypto.randomUUID(),sets});};
 const umpire=async(name,body)=>{const {match}=await get(name);return seat(name,{...body,matchId:match?.id,version:match?.umpireWorkflow.version});};
 try {
  await check(seat('one',{action:'enable'}),403);
  await check(orgAction({action:'enable'}));
  const first=await check(orgAction({action:'add',name:'Rosa Villanueva'}));
  const second=await check(orgAction({action:'add',name:'Dario Tan'}));
  assert.match(first.pin,/^\d{6}$/);assert.notEqual(first.pin,second.pin);
  await check(orgAction({action:'add',name:'rosa villanueva'}),409);
  const [rosa,dario]=(await check(request(demo,'/api/umpires'))).roster;
  const available=await snapshot(demo);
  assert.ok(!JSON.stringify(available).includes('pinHash'));assert.ok(!JSON.stringify(available).includes('pinKey'));
  assert.equal((await request(independent,'/api/umpires','POST',{action:'login',pin:first.pin},{})).status,403);
  await check(seat('one',{action:'login',pin:first.pin}));
  await check(seat('two',{action:'login',pin:second.pin}));
  assert.equal((await get('one')).name,'Rosa Villanueva');
  const prepared={...available.state,status:'live',gameDay:{...available.state.gameDay,restMinutes:0}};
  await check(request(demo,'/api/state','PUT',{state:prepared,expectedRevision:available.revision+2}));
  const matches=(await snapshot(demo)).state.matches.filter(match=>match.stage==='regular');
  const target=matches[0],next=matches.find(match=>match.entryAId!==target.entryAId&&match.entryBId!==target.entryAId&&match.entryAId!==target.entryBId&&match.entryBId!==target.entryBId);
  const dispatch=match=>stateAction({action:'dispatchGame',matchId:match.id,court:1});
  await check(dispatch(target),409);
  await check(orgAction({action:'assignCourt',court:1,umpireId:rosa.id}));
  await check(dispatch(target),409);
  await check(seat('one',{action:'duty',onDuty:true}));
  await check(seat('two',{action:'duty',onDuty:true}));
  await check(dispatch(target));
  assert.equal((await get('one')).match.id,target.id);assert.equal((await get('two')).match,null);
  const seen=await get('one');
  await check(seat('two',{action:'start',matchId:target.id,version:seen.match.umpireWorkflow.version}),403);
  await check(umpire('one',{action:'incorrectPlayers',note:'A substitute arrived at the court.'}));
  await check(umpire('one',{action:'start'}),409);
  let current=(await get('one')).match;
  await check(orgAction({action:'resolvePlayers',matchId:target.id,version:current.umpireWorkflow.version,reason:'Registered players have now arrived.'}));
  await check(umpire('one',{action:'start'}));
  await check(score('one',[{a:12,b:8,complete:false}]));
  await check(orgAction({action:'assignCourt',court:1,umpireId:dario.id,reason:'Shift change'}));
  current=(await get('two')).match;
  assert.deepEqual(current.sets,[{a:12,b:8,complete:false}]);assert.equal(current.umpireWorkflow.handoffs[0].from,rosa.id);
  await check(seat('one',{action:'score',matchId:target.id,version:current.umpireWorkflow.version,sets:[{a:13,b:8,complete:false}]}),403);
  await check(score('two',[{a:31,b:18,complete:true}]));
  assert.equal((await get('two')).match.umpireWorkflow.phase,'awaiting_confirmation');
  assert.equal((await snapshot(demo)).state.matches.find(match=>match.id===target.id).validated,false);
  assert.ok(!(await courtEvents(demo)).some(event=>event.matchId===target.id&&event.gameComplete));
  await check(umpire('two',{action:'submit',a:true,b:false,clear:true}),409);
  await check(umpire('two',{action:'reportDispute',side:'b',reason:'Incorrect recorded score',note:'The second team counted 19.'}));
  await check(umpire('two',{action:'correct',sets:[{a:31,b:19,complete:true}],reason:'Compared the written tally.'}));
  current=(await get('two')).match;
  assert.equal(current.umpireWorkflow.scoreHistory[0].before[0].b,18);
  assert.equal(current.umpireWorkflow.scoreHistory[0].after[0].b,19);
  const submit={action:'submit',matchId:target.id,version:current.umpireWorkflow.version,a:true,b:true,clear:true};
  await check(seat('two',submit));const complete=await snapshot(demo);
  await check(seat('two',submit));assert.equal((await snapshot(demo)).revision,complete.revision);
  assert.equal(complete.state.matches.find(match=>match.id===target.id).validated,true);
  assert.equal((await courtEvents(demo)).filter(event=>event.matchId===target.id&&event.gameComplete).length,1);
  assert.equal((await get('two')).match,null);
  await check(dispatch(next));await check(umpire('two',{action:'acknowledge'}));await check(umpire('two',{action:'start'}));
  await check(score('two',[{a:31,b:20,complete:true}]));
  await check(umpire('two',{action:'reportDispute',side:'both',reason:'Incorrect outcome'}));
  await check(umpire('two',{action:'escalate'}));
  current=(await get('two')).match;
  // Same players as the completed game and none from the detached dispute.
  const afterStart=await snapshot(demo);
  const another={...target,id:'another-practice-game',label:'Practice rematch'};
  await check(request(demo,'/api/state','PUT',{state:{...afterStart.state,matches:[...afterStart.state.matches,another]},expectedRevision:afterStart.revision}));
  await check(dispatch(another),409);
  await check(umpire('two',{action:'releaseDispute',clear:true}),403);
  await check(orgAction({action:'releaseDispute',matchId:next.id,version:current.umpireWorkflow.version,clear:true}));
  assert.equal((await get('two')).match,null);
  const detachedState=(await snapshot(demo)).state;
  const detached=detachedState.matches.find(match=>match.id===next.id);
  assert.deepEqual((await courtEvents(demo)).filter(event=>event.matchId===next.id&&event.kind==='court_released').map(event=>[event.gameComplete,event.available]),[[false,true]]);
  assert.equal(detached.umpireWorkflow.phase,'escalated');assert.equal(detached.validated,false);
  await check(dispatch(another));
  assert.equal((await get('two')).match.id,another.id);
  await check(orgAction({action:'rule',matchId:next.id,version:detached.umpireWorkflow.version,outcome:'finalized',reason:'Reviewed the recorded score sheet.',sets:[{a:31,b:20,complete:true}]}));
  const ruledState=(await snapshot(demo)).state;
  const ruled=ruledState.matches.find(match=>match.id===next.id);
  assert.deepEqual((await courtEvents(demo)).filter(event=>event.matchId===next.id&&event.kind==='court_released').map(event=>[event.gameComplete,event.available]),[[false,true],[true,false]]);
  assert.equal(ruled.umpireWorkflow.phase,'finalized_by_ruling');assert.equal(ruled.umpireWorkflow.confirmed,undefined);
  assert.equal(ruled.umpireWorkflow.releasedAt,detached.umpireWorkflow.releasedAt);
  assert.equal((await get('two')).match.id,another.id);
  await check(umpire('two',{action:'acknowledge'}));
  await check(umpire('two',{action:'start'}));
  await check(score('two',[{a:31,b:21,complete:true}]));
  await check(umpire('two',{action:'reportDispute',side:'a',reason:'Disagreement over a point'}));
  await check(umpire('two',{action:'escalate'}));
  current=(await get('two')).match;
  await check(orgAction({action:'rule',matchId:another.id,version:current.umpireWorkflow.version,outcome:'replay',reason:'Both players requested a replay.',clear:true}));
  const replay=(await snapshot(demo)).state.matches.find(match=>match.id===another.id);
  assert.equal(replay.status,'ready');assert.equal(replay.validated,false);assert.equal(replay.umpireWorkflow,undefined);
  assert.equal(replay.umpireHistory[0].ruling.outcome,'replay');
  assert.equal(replay.umpireHistory[0].dispute.scores[0].b,21);
  await check(orgAction({action:'revokePin',umpireId:dario.id}));
  assert.equal((await get('two')).authenticated,false);
  await check(seat('two',{action:'login',pin:second.pin}),401);
  const publicData=await check(request(demo,'/api/state','GET',undefined,{}));
  assert.doesNotMatch(JSON.stringify(publicData),/umpireDirectory|umpireWorkflow|scoreHistory|handoffs|Shift change/);
  assert.equal((await check(request(independent,'/api/umpires'))).roster.length,0);
 }finally{demo.close();independent.close();}
});
